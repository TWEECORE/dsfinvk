// TestGeneratedFileIsUpToDate is the drift test for schema/tables_gen.go.
func TestGeneratedFileIsUpToDate(t *testing.T) {
	out := filepath.Join(t.TempDir(), "tables_gen.go")
	if err := run(repoIndexXML, out, "schema"); err != nil {
		t.Fatalf("run: %v", err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatalf("read generated: %v", err)
	}
	want, err := os.ReadFile(repoTablesGen)
	if err != nil {
		t.Fatalf("read committed: %v (run: go generate ./schema/)", err)
	}
	if !bytes.Equal(got, want) {
		t.Errorf("schema/tables_gen.go is stale; run: go generate ./schema/\n"+
			"generated %d bytes, committed %d bytes", len(got), len(want))
	}
}

func TestRunIsDeterministic(t *testing.T) {
	dir := t.TempDir()
	a := filepath.Join(dir, "a.go")
	b := filepath.Join(dir, "b.go")
	for _, out := range []string{a, b} {
		if err := run(repoIndexXML, out, "schema"); err != nil {
			t.Fatalf("run(%s): %v", out, err)
		}
	}
	ba, err := os.ReadFile(a)
	if err != nil {
		t.Fatal(err)
	}
	bb, err := os.ReadFile(b)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(ba, bb) {
		t.Error("two runs produced different output")
	}
}

func TestGeneratedHeaderAndPackage(t *testing.T) {
	out := filepath.Join(t.TempDir(), "tables_gen.go")
	if err := run(repoIndexXML, out, "mypkg"); err != nil {
		t.Fatalf("run: %v", err)
	}
	src, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	const header = "// Code generated by internal/gen from index.xml; DO NOT EDIT.\n"
	if !bytes.HasPrefix(src, []byte(header)) {
		t.Errorf("missing generated-code header, got %q", firstLine(src))
	}
	if !bytes.Contains(src, []byte("\npackage mypkg\n")) {
		t.Error("-pkg flag not honored")
	}
}

// TestGeneratedDialectConstants pins the index.xml facts the CSV layer needs:
// every table declares <UTF8/>, the header sits one row above the data, and the
// declared grouping symbol must never be emitted.
func TestGeneratedDialectConstants(t *testing.T) {
	out := filepath.Join(t.TempDir(), "tables_gen.go")
	if err := run(repoIndexXML, out, "schema"); err != nil {
		t.Fatalf("run: %v", err)
	}
	src, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		`(?m)^\tEncoding\s+= "UTF-8"$`,
		`(?m)^\tHeaderRow\s+= 1$`,
		`(?m)^\tDataStartRow\s+= 2$`,
		`grouping must not be emitted`,
	} {
		if !regexp.MustCompile(want).Match(src) {
			t.Errorf("generated source does not match %q", want)
		}
	}
}

func TestParseStripsBOMAndReadsAllTables(t *testing.T) {
	raw, err := os.ReadFile(repoIndexXML)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasPrefix(raw, bom) {
		t.Fatal("fixture lost its BOM; the strip path is no longer exercised")
	}
	ds, err := parse(raw)
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	tables := ds.tables()
	if got, want := len(tables), 20; got != want {
		t.Fatalf("tables = %d, want %d", got, want)
	}
	total := 0
	for _, tbl := range tables {
		total += len(tbl.columns())
	}
	if got, want := total, 219; got != want {
		t.Errorf("columns = %d, want %d", got, want)
	}
	if got, want := tables[0].URL, "cashpointclosing.csv"; got != want {
		t.Errorf("first table = %q, want %q", got, want)
	}
	if got, want := tables[0].Name, "Stamm_Abschluss"; got != want {
		t.Errorf("first table name = %q, want %q", got, want)
	}
}

func TestParseRejectsNonUniformFormat(t *testing.T) {
	raw, err := os.ReadFile(repoIndexXML)
	if err != nil {
		t.Fatal(err)
	}
	cases := map[string][2]string{
		"DecimalSymbol":       {"<DecimalSymbol>,</DecimalSymbol>", "<DecimalSymbol>.</DecimalSymbol>"},
		"DigitGroupingSymbol": {"<DigitGroupingSymbol>.</DigitGroupingSymbol>", "<DigitGroupingSymbol>,</DigitGroupingSymbol>"},
		"ColumnDelimiter":     {"<ColumnDelimiter>;</ColumnDelimiter>", "<ColumnDelimiter>|</ColumnDelimiter>"},
		"TextEncapsulator":    {"<TextEncapsulator>\"</TextEncapsulator>", "<TextEncapsulator>'</TextEncapsulator>"},
		"RangeFrom":           {"<From>2</From>", "<From>3</From>"},
	}
	for name, pair := range cases {
		t.Run(name, func(t *testing.T) {
			// Mutate only the last occurrence so table 20 disagrees with 1..19.
			i := bytes.LastIndex(raw, []byte(pair[0]))
			if i < 0 {
				t.Fatalf("pattern %q not found", pair[0])
			}
			mutated := make([]byte, 0, len(raw))
			mutated = append(mutated, raw[:i]...)
			mutated = append(mutated, pair[1]...)
			mutated = append(mutated, raw[i+len(pair[0]):]...)

			ds, err := parse(mutated)
			if err != nil {
				t.Fatalf("parse: %v", err)
			}
			if _, err := ds.format(); err == nil {
				t.Fatalf("format() accepted non-uniform %s", name)
			} else if !strings.Contains(err.Error(), name[:5]) {
				t.Logf("error message: %v", err)
			}
		})
	}
}

