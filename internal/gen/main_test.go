func firstLine(b []byte) string {
	if i := bytes.IndexByte(b, '\n'); i >= 0 {
		return string(b[:i])
	}
	return string(b)
}

func TestParseRejectsMalformedDocuments(t *testing.T) {
	wrap := func(tables string) []byte {
		return []byte(`<?xml version="1.0" encoding="utf-8"?><DataSet><Version>1.0</Version><Media><Name>CD</Name>` + tables + `</Media></DataSet>`)
	}
	col := func(body string) string {
		return "<VariableColumn>" + body + "</VariableColumn>"
	}
	table := func(url, cols string) string {
		return "<Table><URL>" + url + "</URL><Name>N</Name><UTF8 /><DecimalSymbol>,</DecimalSymbol>" +
			"<DigitGroupingSymbol>.</DigitGroupingSymbol><Range><From>2</From></Range>" +
			"<VariableLength><ColumnDelimiter>;</ColumnDelimiter><RecordDelimiter>&#xD;&#xA;</RecordDelimiter>" +
			"<TextEncapsulator>\"</TextEncapsulator>" + cols + "</VariableLength></Table>"
	}
	ok := col("<Name>A</Name><AlphaNumeric /><MaxLength>5</MaxLength>")

	tests := map[string][]byte{
		"not xml":            []byte("<DataSet"),
		"no tables":          wrap(""),
		"empty URL":          wrap(table("", ok)),
		"duplicate table":    wrap(table("a.csv", ok) + table("a.csv", ok)),
		"no columns":         wrap(table("a.csv", "")),
		"empty column name":  wrap(table("a.csv", col("<Name></Name><Numeric />"))),
		"duplicate column":   wrap(table("a.csv", ok+ok)),
		"both types":         wrap(table("a.csv", col("<Name>A</Name><AlphaNumeric /><Numeric />"))),
		"alpha no maxlength": wrap(table("a.csv", col("<Name>A</Name><AlphaNumeric />"))),
		"maxlength zero":     wrap(table("a.csv", col("<Name>A</Name><AlphaNumeric /><MaxLength>0</MaxLength>"))),
		"numeric maxlength":  wrap(table("a.csv", col("<Name>A</Name><Numeric /><MaxLength>5</MaxLength>"))),
		"negative accuracy":  wrap(table("a.csv", col("<Name>A</Name><Numeric><Accuracy>-1</Accuracy></Numeric>"))),
		"no type":            wrap(table("a.csv", col("<Name>A</Name>"))),
	}
	for name, doc := range tests {
		t.Run(name, func(t *testing.T) {
			if _, err := parse(doc); err == nil {
				t.Error("parse() accepted the document")
			}
		})
	}
}

func TestFormatRejectsMalformedSettings(t *testing.T) {
	build := func(rangeFrom, decimal, encapsulator, record string) *dataSet {
		return &dataSet{Media: []media{{Tables: []xmlTable{{
			URL:                 "a.csv",
			UTF8:                &struct{}{},
			DecimalSymbol:       decimal,
			DigitGroupingSymbol: ".",
			Range: struct {
				From string `xml:"From"`
			}{From: rangeFrom},
			VariableLength: varLength{
				ColumnDelimiter:  ";",
				RecordDelimiter:  record,
				TextEncapsulator: encapsulator,
			},
		}}}}}
	}
	tests := map[string]*dataSet{
		"no tables":                 {},
		"non-numeric Range/From":    build("x", ",", `"`, "\r\n"),
		"Range/From without header": build("1", ",", `"`, "\r\n"),
		"multi-rune DecimalSymbol":  build("2", ",,", `"`, "\r\n"),
		"empty TextEncapsulator":    build("2", ",", "", "\r\n"),
		"empty RecordDelimiter":     build("2", ",", `"`, ""),
	}
	for name, ds := range tests {
		t.Run(name, func(t *testing.T) {
			if _, err := ds.format(); err == nil {
				t.Error("format() accepted the settings")
			}
		})
	}
}

